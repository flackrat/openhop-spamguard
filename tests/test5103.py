from harness import *
def run(m,g):
    g.poll_once(); time.sleep(0.05); g.last_sync=0; g.sync_pending=True; g.poll_once()
m=mock()
for i in range(5): m.add(rname(),f"spam {i} "+rname(10),["82","04","3B"],ago=50-i)
g=guard(m); run(m,g)
b=g.blocks.get("hop:82")
check("repeater block lasts 2 h by default", b and 7000 < b["expires"]-time.time() <= 7200)
m.add("Over The Hill","Test",["44","82","3B"]); m.add(rname(),"more spam "+rname(9),["82","04","3B"]); run(m,g)
st=g.status()
check("genuine-looking held message listed", [h["sender"] for h in st["held"]]==["Over The Hill"])
check("random-name spam not listed", all(not sg.name_score(h["sender"],g.name_res)>=3 for h in st["held"]))
r=g.action("not_spam",{"sender":"Over The Hill","matched":"hop:82","text":"Test"}); run(m,g)
check("Let through trusts them and clears the list", g.status()["held"]==[] and m.decide("Over The Hill","hi",["44","82","3B"])=="allow")
check("repeater block kept", "hop:82" in g.blocks)
g.apply_settings({"hop_block_ttl_seconds":21600})
check("setting can be changed", g.cfg["hop_block_ttl_seconds"]==21600)
g._save_state(force=True); g2=sg.SpamGuard(dict(g.file_cfg))
check("held list survives restart", len(g2.held)==len(g.held))
print(f"\n{sum(c for _,c in RESULTS)}/{len(RESULTS)} passed")
